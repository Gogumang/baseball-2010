/**
 * **경기 장면 상태 0xe — 사람 OK 를 기다리는 자리** (팀 경기·나리 타자편·나리 투수편·미션 공용).
 *
 * 원본 경기 장면(0x104)은 새 타석마다 0xd(타석 준비, 갱신 0x39e14) → 0xe 를 지나고, 0xe 는 **사람 OK 를 받아야만** 0xf 로 간다:
 * ```
 * 39e14  0xd 갱신: 틱 > 0 이고 점수판 [+0xf10]+0x6c ≠ 1 이면 0xbcb49(…, 0xe)          ; 모드 갈림 없음
 * 50674  0xe 진입: 0x504cc(감독 강판 — 모드 3 만 참이 될 수 있다, 504de) 참이면 0x23 으로 빠진다
 * 39bd4  0xe 갱신: 모드 7 이면 그냥 돌아가고, 아니면 화면 전환 객체 [0x140007c] 가 페이드 아웃을 끝냈을 때(+4 ≠ 0 · +0x10 == 2)
 *        페이드 인 0xbdae8(…, 2, 0, 5, 1500) 만 건다 — **시간 제한·자동 진행이 없다**
 * 532b0  사람 조작 객체(vtable 0xd0a14 슬롯 3 0x536bc → 점프표 0xd0a24 칸 0) 0xe 키: −5(OK)·'5'(0x35) 이면
 *        메시지 1(인자 = 지금 상태 0xe) → 0x50c18 이 0xf 예약 · 돌발 0x8f158. 다른 키는 아무 일도 없다. 공격·수비([+0xc])를 안 본다
 * 53874  CPU 조작 객체(vtable 0xd0a60, 생성 0x53718 이 [+0x10] = 1) 갱신: [+0x14] 가 0xf·0x10·0x11 일 때만 움직인다 — 0xe 를 안 넘긴다
 * 49a06  키 처리 0x498d4 끝: 조작 객체 둘(+0xfa0) 중 [+0x10] == 0(사람)에만 키를 넘기고,
 * 49a26  그때 `[+0x1c] == 0xe && [+0x2c](이 상태의 틱) ≤ 2` 면 넘기지 않는다 → 들어선 뒤 세 갱신 안의 OK 는 먹지 않는다
 * ```
 * 0xd 로 들어오는 길(R10 8절): 새 타자(판정 A 0xae24c 의 삼진 갈래 · 판정 B 0xae3e8 의 다음 타자 갈래) · 반 이닝 시작
 * (0x18 의 OK → 0xae3a0) · 교체 연출 0x16 뒤(사람 `#` 교체 확정 · 0xf 진입 0x3d954 의 CPU 대타·CPU 투수 교체) ·
 * 교체 창 취소('#'·CLR → 곧장 0xe, 0x495fc).
 * 자동진행(0x21)은 간이 엔진이 반 이닝을 통째로 돌려 0xd·0xe 를 아예 안 지난다 — 0x21 이 끝나 0x18 이 스스로 OK 를
 * 보낸 뒤(+0x1784, 0x4f928) 다음 사람 타석의 0xe 는 다시 OK 를 기다린다.
 *
 * 진행기는 0xe 에 들어설 때마다 **새 객체**를 하나 만들어 진행 상태에 싣는다. 화면(`useSceneConfirm`)은 객체마다 OK 를 센다 —
 * 진행 상태를 펼쳐 복사해도 같은 객체가 남으니, 화면이 다시 서도(수비 화면을 갔다 와도) 이미 받은 OK 를 잊지 않는다.
 *
 * 원본은 0xe 의 OK 뒤에 돌발 굴림 0x8f158 · 0xf 진입 0x3d954 를 돈다. 팀경기·나리 투수편 진행기는 그 굴림을 OK 를 받을 때
 * 돌린다(`confirmScene` — 0xe 에서도 여는 '#' 교체·강판 물음 0x4994a 를 거쳐도 굴림은 OK 뒤 한 번). 대기는 늘 `enterSceneConfirm`.
 * 미션 세션도 새 타석 대기의 OK 를 받는 화면 콜백에서 0x3d954(CPU 교체)를 묻는다 — 교체가 나면 교체 연출 0x16
 * (`substitutionScene`) 뒤 새 대기를 하나 더 싣는다.
 * ⚠️ **근사**: 나리 타자편 진행기는 아직 그 굴림을 0xe 에 들어서는 걸음에서 미리 다 해 두고 화면이 OK 를 받을 때까지
 * 결과를 내놓지 않는다 — 대기 동안 다른 굴림이 없어 굴림 차례는 같다. 타자편은 '#' 가 막힌다(0x38984 모드 4).
 * 미션(모드 5·6)도 0x38984 가 막는다 — 미션 준비 0xaa57c 가 [ctx+0xa8] = 1 & ~레코드[1] 로 적고 원본 표의 바이트 1 이 모두 짝수라
 * 늘 막힌다(`entities/mission/model/missionSubstitution`). 웹 미션에 '#' 가 없는 것이 원본과 같다.
 * 단 0xe 에서 '*' 메뉴의 자동진행·나가기로 빠지면 원본은 OK 뒤 굴림을 안 도는데 이 둘은 이미 돌았다.
 */
export interface SceneConfirmWait {
  /**
   * 이 걸음 안에서 0xe 를 지난 횟수 — OK 를 이만큼 받아야 0xf 다. 새 타석의 0xe 확인 뒤 0xf 진입 0x3d954 가 CPU 교체를
   * 내면 0x16 → 0xd → 0xe 로 **한 번 더** 와 다시 기다린다 (같은 걸음 안이라 2).
   */
  readonly entries: number
}

/** 새로 0xe 에 들어섰다 — 앞 대기는 이미 OK 를 받은 뒤다 */
export function enterSceneConfirm(): SceneConfirmWait {
  return { entries: 1 }
}

/**
 * 같은 걸음 안에서 0xe 를 한 번 더 지난다 — 방금 만든 대기의 OK 뒤 0xf 진입 0x3d954 가 CPU 교체를 내 0x16 → 0xd → 0xe 로
 * 다시 왔을 때. 앞 대기가 없으면 새 대기와 같다.
 */
export function chainSceneConfirm(previous: SceneConfirmWait | null | undefined): SceneConfirmWait {
  return { entries: (previous?.entries ?? 0) + 1 }
}
